# Jogo de pontuação se baseando em IFs lendo a cor de um alienígena abatido.
alien_color = 'red'

if alien_color == 'green':
    print("Alien verde abatido! +5 pontos")
elif alien_color == 'yellow':
    print("Alien abatido! +10 pontos")
elif alien_color == 'red':
    print("Alien abatido! +15 pontos")