# Constrói os loop das operações finalizadas em acréscimos das variáveis constantes da while para interlaçar os envios do usuário do sistema encravado numa var SOMA cumulativo constante total impressional iterativa format loop.
num = 0
contador = 0
while contador < 5:
    numero = int(input("Digite um numero"))
    contador += 1
    num += numero
print(f"O valor desta soma é {num}" )